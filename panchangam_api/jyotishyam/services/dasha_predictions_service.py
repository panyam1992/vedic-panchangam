def generate_dasha_antardasha_analysis(dasha_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Build comprehensive Dasha-Antardasha analysis for the running Mahadasha
    and all 9 Bhuktis within it, complete with dates, status, and Shastric predictions.
    """
    curr_m = dasha_data.get("current_mahadasha")
    if not curr_m:
        return {}

    m_lord_en = curr_m.get("lord", "Rahu")
    m_lord_te = curr_m.get("lord_te", "రాహువు")

    # 1. Mahadasha In-depth Interpretation
    maha_pred = MAHADASHA_PREDICTIONS.get(m_lord_en, MAHADASHA_PREDICTIONS["Rahu"])

    # 2. Detailed Interpretation for each of the 9 Bhuktis
    bhuktis = dasha_data.get("current_bhuktis", [])
    enriched_bhuktis = []

    for b in bhuktis:
        b_lord_en = b.get("lord", "")
        b_lord_te = b.get("lord_te", "")

        key = (m_lord_en, b_lord_en)
        shastra_text = BHUKTI_SHASTRA_TEXTS.get(key)
        if not shastra_text:
            shastra_text = get_default_bhukti_text(m_lord_en, b_lord_en, m_lord_te, b_lord_te)

        enriched_bhuktis.append({
            "lord": b_lord_en,
            "lord_te": b_lord_te,
            "full_name": f"{m_lord_te}లో {b_lord_te} అంతర్దశ",
            "start_date": b.get("start_date"),
            "end_date": b.get("end_date"),
            "is_active": b.get("is_active", False),
            "prediction": shastra_text
        })

    active_b = next((b for b in enriched_bhuktis if b["is_active"]), enriched_bhuktis[0] if enriched_bhuktis else None)

    return {
        "current_mahadasha_name": m_lord_te,
        "current_mahadasha_overview": maha_pred,
        "active_bhukti": active_b,
        "all_bhuktis": enriched_bhuktis
    }
